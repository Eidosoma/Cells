"""FR-43 part 3 references: a fast self-check of the committed results, with no engine import.

The results in validation/fr43_part3/references/results/ are the code-blind same-draws reference.
This test recomputes their checks from spec/ and results/ alone:

- the premise: the draws regenerated by the references' own Threefry-2x32 (no JAX) equal
  spec/draws.json bit for bit, and the hash meets Random123's known-answer vectors;
- per world, with this file's own assembly of the spec's law as one augmented linear system
  z' = M z, z = (n_cell, n_node, H, transferred, produced, cleared, 1), propagated by
  scipy.linalg.expm from each reported event (a third evaluation, apart from the closed form and
  the ODE): the hazard reaches E_k = -ln(u1_k) at each reported time, the pools and totals
  match, the channel rule picks the reported channel, the jump gives the reported counts, the
  accounting identities hold, no event is missed before the horizon, and the samples match;
- the stated accuracy: the closed form against the ODE within the spec's target.
"""

import importlib.util
import json
import math
import pathlib

import numpy as np
import pytest
from scipy.linalg import expm

ROOT = pathlib.Path(__file__).resolve().parents[2]
REF = ROOT / "validation" / "fr43_part3" / "references"
SPEC = json.loads((REF / "spec" / "part3.json").read_text())
DRAWS = json.loads((REF / "spec" / "draws.json").read_text())
WORLDS = {w["id"]: w for w in SPEC["worlds"]}

TIME_TOL_S = 1e-12          # a hazard crossing, as a time (the target is 1e-10 s)
AMOUNT_REL_TOL = 1e-12      # the spec's amount target, relative
AMOUNT_ABS_FLOOR = 1e-15    # for amounts that are exactly zero
IDENTITY_TOL_FMOL = 1e-13   # accounting identities on the reported binary64 values

EVENT_KEYS = {"k", "time_s", "channel", "counts_after", "cell_S_fmol", "node_S_fmol", "transferred_fmol"}
SAMPLE_KEYS = {"time_s", "cell_S_fmol", "node_S_fmol", "counts", "transferred_fmol"}
TURNOVER_KEYS = {"turnover_produced_fmol", "turnover_cleared_fmol"}


def _load_stream_draws():
    spec = importlib.util.spec_from_file_location("fr43_part3_stream_draws", REF / "stream_draws.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _ff(n, r):
    return 0 if r > n else math.prod(range(n - r + 1, n + 1))


def _turnover(world):
    t = world["turnover"] or {}
    return t.get("production_cell_fmol_per_s", 0.0), t.get("clearance_node_per_s", 0.0)


def _matrix(world, counts):
    """z' = M z for z = (n_cell, n_node, H, transferred, produced, cleared, 1) at fixed counts."""
    vol = world["volumes_pL"]
    g = world["transfer"]["conductance_pL_per_s_per_unit"]
    big_g = sum(g[s] * n for s, n in counts.items())
    p_cell, k_node = _turnover(world)
    flux = np.array([big_g / vol["cell"], -big_g / vol["node"]])     # J = G (c_cell - c_node)
    m = np.zeros((7, 7))
    m[0, :2], m[0, 6] = -flux, p_cell
    m[1, :2] = flux
    m[1, 1] -= k_node
    for ch in world["channels"]:
        coef = ch["rate_constant_per_s"] * math.prod(_ff(counts[s], r) for s, r in ch["reactants"].items())
        read = ch["read"]
        if read is None:
            m[2, 6] += coef
        else:
            assert read["species"] == "S" and read["order"] == 1
            m[2, {"cell": 0, "node": 1}[read["at"]]] += coef / vol[read["at"]]
    m[3, :2] = flux
    m[4, 6] = p_cell
    m[5, 1] = k_node
    return m


def _propagate(world, counts, amounts, tau):
    """amounts = (cell, node, transferred, produced, cleared) -> z(tau), H restarted at 0."""
    z0 = np.array([amounts[0], amounts[1], 0.0, amounts[2], amounts[3], amounts[4], 1.0])
    return expm(_matrix(world, counts) * tau) @ z0


def _propensities(world, cell, node, counts):
    conc = {"cell": cell / world["volumes_pL"]["cell"], "node": node / world["volumes_pL"]["node"]}
    out = []
    for ch in world["channels"]:
        a = ch["rate_constant_per_s"] * math.prod(_ff(counts[s], r) for s, r in ch["reactants"].items())
        if ch["read"] is not None:
            a *= conc[ch["read"]["at"]]
        out.append(a)
    return out


def _channel(props, u2):
    """The spec's rule: the first j with c_j > min(u2 a0, nextafter(a0, 0))."""
    a0 = sum(props)
    threshold = min(u2 * a0, math.nextafter(a0, 0.0))
    c = 0.0
    for j, a in enumerate(props):
        c += a
        if c > threshold:
            return j
    raise AssertionError("no channel chosen")


def _amounts(row, turnover):
    vals = [row["cell_S_fmol"], row["node_S_fmol"], row["transferred_fmol"]]
    vals += [row["turnover_produced_fmol"], row["turnover_cleared_fmol"]] if turnover else [0.0, 0.0]
    return vals


def _close(got, want):
    return abs(got - want) <= AMOUNT_REL_TOL * abs(want) + AMOUNT_ABS_FLOOR


def test_draws_premise():
    sd = _load_stream_draws()
    # Random123's known-answer vectors for Threefry-2x32 with 20 rounds: (key, counter) -> output
    for key, ctr, out in (((0, 0), (0, 0), (0x6B200159, 0x99BA4EFE)),
                          ((0xFFFFFFFF, 0xFFFFFFFF), (0xFFFFFFFF, 0xFFFFFFFF), (0x1CB996FC, 0xBB002BE7)),
                          ((0x13198A2E, 0x03707344), (0x243F6A88, 0x85A308D3), (0xC4923A9C, 0x483DF7A0))):
        assert sd.threefry2x32(key, ctr) == out
    fresh = sd.regenerate(SPEC, sd.scratch_uniforms)
    assert set(fresh) == set(DRAWS["worlds"]) == set(WORLDS)
    for wid, row in fresh.items():
        saved = DRAWS["worlds"][wid]
        assert (row["u1"], row["u2"]) == (saved["u1"], saved["u2"]), wid
    check = json.loads((REF / "results" / "draws_check.json").read_text())
    assert check["identical"] and set(check["routes"]) == {"scratch", "jax"}


@pytest.mark.parametrize("wid", sorted(WORLDS))
def test_world_result(wid):
    world = WORLDS[wid]
    res = json.loads((REF / "results" / f"{wid}.json").read_text())
    turnover = world["turnover"] is not None
    names = [s["id"] for s in world["unit_states"]]
    chan_ids = [ch["id"] for ch in world["channels"]]
    horizon = world["horizon_s"]
    u1 = [float.fromhex(h) for h in DRAWS["worlds"][wid]["u1"]]
    u2 = [float.fromhex(h) for h in DRAWS["worlds"][wid]["u2"]]
    p_cell = _turnover(world)[0]
    init = world["initial_amounts_fmol"]
    total0 = init["cell"] + init["node"]

    assert {"world", "events", "samples", "method", "accuracy"} <= set(res) and res["world"] == wid
    extra = TURNOVER_KEYS if turnover else set()
    assert all(set(ev) == EVENT_KEYS | extra for ev in res["events"])
    assert all(set(sm) == SAMPLE_KEYS | extra for sm in res["samples"])

    # the events: from each reported state to the next reported crossing
    t_prev, counts = 0.0, {n: world["initial_counts"][n] for n in names}
    amounts = [init["cell"], init["node"], 0.0, 0.0, 0.0]
    starts = [(t_prev, dict(counts), list(amounts))]
    for k, ev in enumerate(res["events"]):
        assert ev["k"] == k and t_prev < ev["time_s"] <= horizon
        z = _propagate(world, counts, amounts, ev["time_s"] - t_prev)
        target = -math.log(u1[k])
        rate = sum(_propensities(world, z[0], z[1], counts))
        assert abs(z[2] - target) / rate <= TIME_TOL_S, (k, z[2], target)
        reported = _amounts(ev, turnover)
        for got, want in zip((z[0], z[1], z[3], z[4], z[5]), reported):
            assert _close(got, want), (k, got, want)
        j = _channel(_propensities(world, ev["cell_S_fmol"], ev["node_S_fmol"], counts), u2[k])
        assert chan_ids[j] == ev["channel"], k
        ch = world["channels"][j]
        counts = {n: counts[n] - ch["reactants"].get(n, 0) + ch["products"].get(n, 0) for n in names}
        assert ev["counts_after"] == counts, k
        cell, node, moved, made, cleared = reported
        assert abs(cell + node + cleared - made - total0) <= IDENTITY_TOL_FMOL, k
        assert abs(moved - (init["cell"] + made - cell)) <= IDENTITY_TOL_FMOL, k
        assert abs(made - p_cell * ev["time_s"]) <= IDENTITY_TOL_FMOL, k
        t_prev, amounts = ev["time_s"], reported
        starts.append((t_prev, dict(counts), list(amounts)))

    # no event is missed before the horizon, and the reported next one crosses after it
    k_next = len(res["events"])
    target = -math.log(u1[k_next])
    assert _propagate(world, counts, amounts, horizon - t_prev)[2] < target
    after = res["diagnostics"]["next_event_after_horizon"]
    assert after["k"] == k_next and after["time_s"] > horizon
    z = _propagate(world, counts, amounts, after["time_s"] - t_prev)
    assert abs(z[2] - target) / sum(_propensities(world, z[0], z[1], counts)) <= TIME_TOL_S

    # the samples, each from the last reported event at or before it
    assert [s["time_s"] for s in res["samples"]] == world["sample_times_s"]
    for sm, sdiag in zip(res["samples"], res["sample_diagnostics"]):
        t0, n0, a0 = [s for s in starts if s[0] <= sm["time_s"]][-1]
        z = _propagate(world, n0, a0, sm["time_s"] - t0)
        assert sm["counts"] == n0, sm["time_s"]
        for got, want in zip((z[0], z[1], z[3], z[4], z[5]), _amounts(sm, turnover)):
            assert _close(got, want), (sm["time_s"], got, want)
        assert abs(z[2] - sdiag["hazard_since_last_event"]) <= 1e-12 * max(1.0, z[2])

    # the draws each event used, and the stated accuracy against the spec's target
    stream = DRAWS["worlds"][wid]
    for k, row in enumerate(res["event_diagnostics"]):
        assert (row["u1_hex"], row["u2_hex"]) == (stream["u1"][k], stream["u2"][k])
    acc = res["accuracy"]
    for key in ("closed_form_vs_radau", "closed_form_vs_dop853", "radau_vs_dop853"):
        assert acc[key]["same_events_channels_and_counts"] and acc[key]["same_sample_counts"], key
    radau = acc["closed_form_vs_radau"]
    assert radau["max_event_time_diff_s"] <= acc["target"]["event_time_s"] == 1e-10
    assert radau["max_amount_rel_diff"] <= acc["target"]["amount_relative"] == 1e-12
    assert acc["radau_meets_target"] is True
    assert acc["closed_form_50_vs_70_digits_arithmetic_only"]["max_amount_rel_diff"] < 1e-30
