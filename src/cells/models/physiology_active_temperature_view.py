"""Complete held active rates under an explicit isothermal parameter policy.

Original checkpoint validation precedes the private coefficient projection.
No projected ordinary spec/checkpoint or accepted history is returned.
"""

from dataclasses import dataclass, replace
from numbers import Real
from types import MappingProxyType

import numpy as np

from cells.core import physiology_active_temperature as contract
from cells.models import physiology_permeability_view as ordinary
from cells.models import physiology_temperature_view as original
from cells.processes.electrochemistry import F, R

KIND = "cells.physiology_active_temperature_view@1"
IMPLEMENTATIONS = {
    key: value for key, value in original.IMPLEMENTATIONS.items() if key in contract.MODEL_TYPES
}
PROJECTED_FIELDS = frozenset(
    (
        "temperature",
        "pump_drive",
        "er_temperature",
        "er_standard_mu_RT",
        "er_delta_mu_RT",
        "pmca_dg",
        "er_pump_dg0",
    )
)


@dataclass(frozen=True, slots=True)
class ActiveTemperatureView:
    preparation: contract.Preparation
    runtime_layout: object
    readouts: object
    derivative: object
    coefficient_audit: object
    thermodynamic_assumptions: object
    admission: object

    @property
    def field(self):
        return self.readouts.field


def _coefficient_projection(spec, temperature_K):
    """Private validator input only; never a parsed or accepted ordinary model.

    Maintained PMCA/ER energies retain their declared numeric-mM J/mol standard.
    Finite pool bridges are regenerated by the existing shared-pool projection
    at the held T, preserving the distinct input standard conventions.
    """
    target = float(temperature_K)
    values = dict(temperature_K=target)
    if hasattr(spec.model, "stores"):
        ratio = contract.REFERENCE_TEMPERATURE_K / target
        values["stores"] = tuple(
            replace(
                store,
                temperature_K=target,
                species=tuple(
                    replace(row, standard_mu_RT=row.standard_mu_RT * ratio) for row in store.species
                ),
            )
            for store in spec.model.stores
        )
    return replace(spec, model=replace(spec.model, **values))


def _runtime(spec, layout, implementation, target):
    projection = _coefficient_projection(spec, target)
    _, proposed = implementation.initial_values(projection)
    changed, replacements = [], {}
    for key in layout._fields:
        before, after = np.asarray(getattr(layout, key)), np.asarray(getattr(proposed, key))
        if before.shape != after.shape or before.dtype != after.dtype:
            raise ValueError("Held coefficient projection changed an owner axis/type: " + key)
        if not np.array_equal(before, after):
            if key not in PROJECTED_FIELDS:
                raise ValueError(
                    "Held coefficient projection changed an original anchor/parameter: " + key
                )
            changed.append(key)
            replacements[key] = after
    runtime = layout._replace(**replacements)
    return runtime, projection, tuple(changed)


def evaluate(spec, state, layout, control, binding, memory, *, time_s, events_enabled, step_s):
    contract.validate_source(spec)
    if (
        not isinstance(step_s, Real)
        or isinstance(step_s, (bool, np.bool_))
        or not np.isfinite(step_s)
        or step_s <= 0
    ):
        raise ValueError("Declare a finite positive explicit held active-rate step")
    rounding = 8 * np.finfo(np.float64).eps * max(spec.experiment.end_time, spec.execution.dt)
    if step_s > spec.execution.dt + rounding:
        raise ValueError("Held active-rate step exceeds the original nominal step")
    preparation = contract.prepare(
        spec, binding, memory, time_s=time_s, events_enabled=events_enabled
    )
    implementation = IMPLEMENTATIONS[type(spec.model)]
    initial, expected = implementation.initial_values(spec)
    ordinary._exact_layout(layout, expected)
    actual = ordinary._state(state, initial)
    held = ordinary._control(spec, control)
    # Original histories and accounting are validated solely at their original
    # temperature, chemical references, drives and capacitor anchors.
    original_checks = implementation.check_values(actual, spec)
    table = type(held)(*(value[None] for value in held))
    implementation.check_steps(spec, np.asarray([step_s]), table)
    runtime, projection, changed = _runtime(
        spec, layout, implementation, preparation.state.temperature_K
    )
    # Reuse the same gate/loss/turnover criteria with all held coefficients.
    # This private validation projection is never checkpoint admission.
    implementation.check_steps(projection, np.asarray([step_s]), table)
    if not implementation.domain_valid(actual, runtime, runtime.active, xp=np):
        raise contract.TemperatureRejected(
            "Held active coefficients violate the physical stage domain",
            dict(preparation=preparation),
        )
    values = implementation.readouts(actual, held, runtime, xp=np)
    derivative, field = values.derivative, values.field
    trial = dict(
        preparation=preparation,
        runtime_layout=ordinary._immutable_tree(runtime),
        readouts=ordinary._immutable_tree(values),
    )
    if (
        not values.valid
        or not field.converged
        or any(not np.isfinite(value).all() for value in derivative)
        or abs(float(field.energy_balance_pJ_s)) > original.MAX_STAGE_ENERGY_RESIDUAL_PJ_S
        or any(
            np.min(getattr(derivative, name), initial=0) < -1e-12
            for name in derivative._fields
            if name.endswith("_dissipated_energy_pJ")
        )
    ):
        raise contract.TemperatureRejected(
            "Invalid full held active rates/field/energy/dissipation", trial
        )
    passive_fraction = ordinary._passive_fraction(
        actual, held, runtime, field, implementation, float(step_s)
    )
    fuel_fraction = 0.0
    if hasattr(runtime, "energy_initial_amount_fmol"):
        amounts = ordinary.fuel.energy_amounts(actual, runtime)
        parent = values.parent if hasattr(values, "parent") else values
        gross = parent.exchange.gross_hydrolysis_fmol_s + parent.exchange.gross_synthesis_fmol_s
        fraction = np.where(
            runtime.active, gross / np.where(runtime.active, np.min(amounts, axis=0), 1.0), 0.0
        )
        fuel_fraction = float(step_s) * float(np.max(fraction, initial=0))
    if (
        not np.isfinite([passive_fraction, fuel_fraction]).all()
        or passive_fraction > ordinary.MAX_PASSIVE_FRACTION_PER_STEP
        or fuel_fraction > ordinary.MAX_FUEL_FRACTION_PER_STEP
    ):
        raise contract.TemperatureRejected(
            "Held active rates exceed unchanged gross-turnover ceilings", trial
        )
    audit = MappingProxyType(
        dict(
            policy=contract.POLICY,
            changed_layout_fields=changed,
            permitted_layout_fields=tuple(sorted(PROJECTED_FIELDS)),
            gas_constant_J_mol_K=R,
            faraday_C_mol=F,
            fixed_standard_J_mol_ER=True,
            fixed_forward_rate_coefficients=True,
            maintained_calcium_standard="declared_numeric_mM_J_mol_fixed",
            finite_calcium_projection="deltaG0_1M_minus_RT_ln1000_at_live_pool_T",
            source_definition_sha256=spec.fingerprint,
        )
    )
    assumptions = MappingProxyType(
        dict(
            policy=contract.POLICY,
            held_temperature_K=float(preparation.state.temperature_K),
            reference_temperature_K=contract.REFERENCE_TEMPERATURE_K,
            kinetic_scaling="fixed_empirical_curves_with_live_voltage_calcium_feedback",
            native_split_semantics="separate_native_configured_runtime_split_evidence",
            heat_capacity_defined=False,
            accepted_heat_pJ=None,
            accepted_thermal_transition=False,
            accepted_changed_temperature_checkpoint=False,
            chemical_standard_dependence="declared_fixed_J_mol_isothermal_family_not_calibrated_thermal_response",
        )
    )
    admission = MappingProxyType(
        dict(
            kind=KIND,
            policy=contract.POLICY,
            binding_identity=binding.identity,
            source_definition_sha256=spec.fingerprint,
            step_s=float(step_s),
            original_balance_checks=MappingProxyType(dict(original_checks)),
            held_control=ordinary._immutable_tree(held),
            passive_fraction=passive_fraction,
            fuel_fraction=fuel_fraction,
            passive_limit=ordinary.MAX_PASSIVE_FRACTION_PER_STEP,
            fuel_limit=ordinary.MAX_FUEL_FRACTION_PER_STEP,
            stage_energy_residual_pJ_s=float(field.energy_balance_pJ_s),
            accepted_thermal_stepping=False,
            checkpoint_admission=False,
        )
    )
    return ActiveTemperatureView(
        preparation,
        ordinary._immutable_tree(runtime),
        ordinary._immutable_tree(values),
        ordinary._immutable_tree(derivative),
        audit,
        assumptions,
        admission,
    )
