def closure(law, out=None):
    """law's REQUIRES, transitively and in order, then law."""
    out = [] if out is None else out
    for required in OPERATORS[law].REQUIRES:
        closure(required, out)
    if law not in out:
        out.append(law)
    return out


def sequence(*laws):
    """The composition of the laws with their closures, each law once at its first place."""
    out = []
    for law in laws:
        for x in closure(law):
            if x not in out:
                out.append(x)
    return tuple(out)


def errors(laws):
    inner = pump_composite.INNERS[INNER]
    return pump_composite.structure_errors(inner, tuple(OPERATORS[k] for k in laws))


def family(law):
    return law.split("@")[0]


def in_order(a, b):
    return tuple(sorted((a, b), key=LAWS.index))


# ------------------------------------------------------------------ refusals from the messages

READS = re.compile(r"^(\S+) reads (\S+) as declared, but (\S+) (provides|closes) it$")
MASK = re.compile(r"^(\S+) has closers or a provider, never both \((\S+) provides it\)$")
PROVIDERS = re.compile(r"^two providers of the view field (\S+)$")
OWNERS = re.compile(r"^two owners of one (state|layout|control) field$")
COLUMN = re.compile(r"^(\S+) adds the column (\S+), which (\S+) owns$")
# The order of a current read (docs/OPERATOR_COMPOSITION_DESIGN.md §5, C2): a change at the
# reader's own stage by a later operator.
ORDER = re.compile(r"^(\S+) reads the view (\S+) at stage (\S+) before (\S+) changes it there$")
OWNED = {"state": "STATE_AXES", "layout": "LAYOUT_FIELDS", "control": "CONTROL_FIELDS"}


def refusals(laws, messages):
    """The refusals (kind, first law, second law, field) behind one composition's messages."""
    ops = [OPERATORS[k] for k in laws]
    found = set()
    for message in messages:
        if m := READS.match(message):
            reader, name, other, how = m.groups()
            found.add(("reads" if how == "provides" else "reads-closed", reader, other, name))
        elif m := MASK.match(message):
            name, provider = m.groups()
            found |= {("mask", provider, op.LAW_ID, name) for op in ops if op.CLOSES}
        elif m := PROVIDERS.match(message):
            providers = [op.LAW_ID for op in ops if m.group(1) in op.VIEW_FIELDS]
            for i, a in enumerate(providers):
                for b in providers[i + 1 :]:
                    found.add(("providers", *in_order(a, b), m.group(1)))
        elif m := OWNERS.match(message):
            attribute = OWNED[m.group(1)]
            for i, a in enumerate(ops):
                for b in ops[i + 1 :]:
                    if set(getattr(a, attribute)) & set(getattr(b, attribute)):
                        found.add(("owners", *in_order(a.LAW_ID, b.LAW_ID), m.group(1)))
        elif m := COLUMN.match(message):
            found.add(("column", m.group(1), m.group(3), None))
        elif m := ORDER.match(message):
            reader, name, _, changer = m.groups()
            found.add(("order", reader, changer, name))
        else:
            raise ValueError(f"Unrecognised composition error {message!r} in {laws}")
    out = set()  # Two versions of one law own the same fields, columns and views: one refusal.
    for kind, a, b, name in found:
        if kind in ("mask", "providers", "owners", "column", "order") and family(a) == family(b):
            out.add(("versions", *in_order(a, b), None))
        else:
            out.add((kind, a, b, name))
    return out


def matrix():
    """{(A, B): {"sequence", "refusals"}} for every ordered pair of distinct laws."""
    cells = {}
    for a in LAWS:
        if errors(sequence(a)):
            raise ValueError(f"{a} is refused alone (with its requirements)")
        for b in LAWS:
            if a != b:
                laws = sequence(a, b)
                cells[(a, b)] = dict(sequence=laws, refusals=refusals(laws, errors(laws)))
    return cells


