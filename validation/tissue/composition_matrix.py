"""Which composite operators compose: the composition matrix (D156; the architecture block, item 2).

Two layers, rendered together into docs/PUMP_COMPOSITE.md ("Which operators compose") between the
markers START and END by `python -m validation.tissue.composition_matrix --write`:

1. **The declarations.** For every ordered pair of distinct registered operator laws (A, B), the
   composition is A's REQUIRES closure and A, then B's closure and B, each law once at its first
   place, on @3's adapter. pump_composite.structure_errors checks it from the declarations alone,
   with no definition and no compile. Each error is parsed into a refusal: who reads, provides,
   closes or owns which field against whom. A message this module does not recognise is an error.
2. **The rules at the definition** (RULES). Composition rules in the operators' check_definition
   need a definition. A law-level rule refuses a pair or an order whatever the data: where the
   declarations admit the pair it marks the matrix ("d"), and where they refuse it too it is a
   second wall. A data-level rule is a condition on routes, onsets, slots, schedules or the
   solver, and marks nothing. Each rule cites its check and the test that asserts it.

From the rules that read the solver (their `solver` key) the block also gives the view per solver
(D349 item 3; solver_cells): each operator, with its requirements, under each solver and
field-solver pair a composite admits, with the rule that decides a cell that is not a tick.

Every refusal carries a tag (TAGS, RULES):
* **nominal**: in no admissible definition can the other operator change a slot the reader reads
  or acts on, so a finer declaration would admit the pair without new physics (slot-scoped
  provision, door S of docs/BATH_SCHEDULE_DESIGN.md §3.1). Each nominal tag cites the code.
* **real**: everything else, including "real, not shown nominal".

tests/unit/test_composition_matrix.py regenerates the block and compares it with the document. It
also fails on an unrecognised message, an untagged refusal, a tag that no refusal uses, a
registered law missing from the document's operator table, and a cited check or test that does
not exist. A new operator therefore comes with its refusals' tags and a regenerated block.
"""

