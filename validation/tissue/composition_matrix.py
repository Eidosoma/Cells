def marked():
    """{(A, B): rule} for the cells a law-level rule refuses though the declarations admit them."""
    out = {}
    for rule in RULES:
        for pair in rule.get("marks", ()):
            out[pair] = rule
    return out


def solver_rows():
    """[(rule, its SolverRefusal)] in RULES' order: the numbers of the view per solver's marks."""
    return [(rule, refusal) for rule in RULES for refusal in rule.get("solver", ())]


def solver_cells():
    """{(law, solver pair): (refused, conditional)}: the numbers (solver_rows, from 1) of the rules
    that refuse the law, with its requirements, under the pair whatever the definition, and of
    those that refuse it under a condition (none listed where it is refused in any case)."""
    rows = solver_rows()
    for rule, refusal in rows:
        known = {*refusal.laws, *refusal.beside} <= set(LAWS)
        if not (known and refusal.laws and refusal.pairs and {*refusal.pairs} <= {*SOLVER_PAIRS}):
            raise ValueError(f"{rule['rule']}: {refusal} names an unknown law or solver pair")
        if refusal.beside and refusal.when or refusal.test and not defines(refusal.test):
            raise ValueError(f"{rule['rule']}: {refusal} has two conditions or no such test")
    cells = {}
    for law in LAWS:
        for pair in SOLVER_PAIRS:
            marks = {True: [], False: []}  # Conditional or not.
            for k, (_, refusal) in enumerate(rows, 1):
                if pair in refusal.pairs and set(closure(law)) & set(refusal.laws):
                    marks[bool(refusal.beside or refusal.when)].append(k)
            refused = tuple(marks[False])
            cells[(law, pair)] = (refused, () if refused else tuple(marks[True]))
    return cells


def defines(cite):
    """Whether "path::name" or "path::Class.method" names a function or class in that file."""
    path, name = cite.split("::")
    tree = ast.parse((ROOT / path).read_text())
    scope = tree.body
    for part in name.split("."):
        found = [
            n for n in scope if isinstance(n, ast.FunctionDef | ast.ClassDef) and n.name == part
        ]
        if not found:
            return False
        scope = found[0].body
    return True


# ------------------------------------------------------------------ rendering


def short(law):
    return type(OPERATORS[law]).__module__.rsplit(".", 1)[1]


def number(law):
    return LAWS.index(law) + 1


def named(law):
    return f"{short(law)} ({number(law)})"


def fields(names):
    return ", ".join(f"`{n}`" for n in names)


def describe(kind, a, b, names):
    them = "it" if len(names) == 1 else "them"
    if kind == "reads":
        return f"{named(a)} reads {fields(names)} as declared; {named(b)} provides {them}"
    if kind == "reads-closed":
        return f"{named(a)} reads {fields(names)} as declared; {named(b)} closes {them}"
    if kind == "mask":
        return f"{named(a)} provides {fields(names)} beside the closer {named(b)}"
    if kind == "providers":
        return f"{named(a)} and {named(b)} both provide {fields(names)}"
    if kind == "versions":
        return f"{named(a)} and {named(b)} are two versions of one law"
    if kind == "owners":
        return f"{named(a)} and {named(b)} both own {', '.join(names)} fields"
    if kind == "order":
        return f"{named(a)} reads the view {fields(names)} before {named(b)} changes {them}"
    return f"{named(a)} adds columns that {named(b)} owns"


def render(cells=None):
    cells = matrix() if cells is None else cells
    marks = marked()
    lines = [START, "", "| # | Operator law | Requires | Provides | Closes | Reads as declared |"]
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for law in LAWS:
        op = OPERATORS[law]
        requires = ", ".join(str(number(x)) for x in op.REQUIRES)
        row = (number(law), f"`{law}`", requires, fields(op.VIEW_FIELDS), fields(op.CLOSES))
        lines.append("| " + " | ".join(map(str, (*row, fields(op.CONFLICTS_VIEW)))) + " |")
    lines += [
        "",
        "Row: the earlier operator in the list; column: the later. ✓ admitted by the "
        "declarations; R refused, with a real conflict among the refusals; n refused, every "
        "refusal nominal; d admitted by the declarations, refused at the definition by a "
        "law-level rule; · the same law.",
        "",
        "| | " + " | ".join(str(i) for i in range(1, len(LAWS) + 1)) + " |",
        "| --- |" + " --- |" * len(LAWS),
    ]
    for a in LAWS:
        row = []
        for b in LAWS:
            if a == b:
                row.append("·")
                continue
            found = cells[(a, b)]["refusals"]
            if not found:
                row.append("d" if (a, b) in marks else "✓")
            else:
                row.append("R" if any(TAGS[r][0] == REAL for r in found) else "n")
        lines.append(f"| **{number(a)}** | " + " | ".join(row) + " |")
    pairs = defaultdict(int)
    for cell in cells.values():
        for refusal in cell["refusals"]:
            pairs[refusal] += 1
    merged = defaultdict(list)  # Rows with one kind, laws, tag and reason share a line.
    for refusal in sorted(
        pairs, key=lambda r: (LAWS.index(r[1]), LAWS.index(r[2]), r[0], str(r[3]))
    ):
        kind, a, b, name = refusal
        tag, why, _ = TAGS[refusal]
        merged[(kind, a, b, tag, why)].append((name, pairs[refusal]))
    lines += [
        "",
        "**Refusals from the declarations**, with the number of ordered pairs each refuses:",
        "",
        "| Refusal | Pairs | Tag | Why |",
        "| --- | --- | --- | --- |",
    ]
    for (kind, a, b, tag, why), entries in merged.items():
        names = [n for n, _ in entries if n is not None]
        count = max(c for _, c in entries)
        lines.append(f"| {describe(kind, a, b, names)} | {count} | {tag} | {why} |")
    lines += [
        "",
        "**Rules at the definition** (each operator's `check_definition`; law-level rules refuse "
        "a pair or an order whatever the data, data-level rules a condition):",
        "",
        "| Rule | Operators | Level | Check | Test | Tag | Why |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for rule in RULES:
        laws = ", ".join(str(number(x)) for x in rule["laws"])
        level = rule["level"]
        if rule.get("marks"):
            level += ", marks " + ", ".join(f"{number(a)}→{number(b)}" for a, b in rule["marks"])
        elif rule.get("behind"):
            level += ", behind a refusal of the declarations"
        lines.append(
            f"| {rule['rule']} | {laws} | {level} | `{rule['check']}` | `{rule['test']}` | "
            f"{rule['tag']} | {rule['why']} |"
        )
    lines += ["", *render_solvers(), "", END]
    return "\n".join(lines)


def render_solvers():
    """The view per solver: the pairs, the cells and the refusals their marks name."""
    cells, columns = solver_cells(), [chr(ord("A") + k) for k in range(len(SOLVER_PAIRS))]
    lines = [
        "**Per solver** (D349): each operator, with its requirements, under each solver and "
        "field-solver pair a composite admits, from the rules above that read the solver. ✓ none "
        "of them refuses it; R refused whatever the definition; c conditional, refused under the "
        "condition given. The number names the refusal, listed below the table with its check and "
        "the test that asserts it (none: no test does). A ✓ is no qualification (D143).",
        "",
        "Not in the table: the rules above that hold under every solver (the species cap among "
        "them); what @3 itself refuses per solver whatever the operators (declared kinds and the "
        "heat booking options under RK4, a blocked channel population under the "
        "implicit-conductance solver); and the step checks, which bound the step size and let the "
        "implicit-conductance solver run only with `execution.energy_check`. An operator that the "
        "declarations refuse beside every coupled one (the matrix above) keeps its ✓ under RK4.",
        "",
        "| Column | Solver | Field solver |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {c} | `{s}` | `{f}` |" for c, (s, f) in zip(columns, SOLVER_PAIRS, strict=True)]
    lines += [
        "",
        "| # | Operator law | " + " | ".join(columns) + " |",
        "| --- | --- |" + " --- |" * len(columns),
    ]
    for law in LAWS:
        row = []
        for pair in SOLVER_PAIRS:
            refused, conditional = cells[(law, pair)]
            marks = [f"R{k}" for k in refused] + [f"c{k}" for k in conditional]
            row.append(" ".join(marks) or "✓")
        lines.append(f"| {number(law)} | `{law}` | " + " | ".join(row) + " |")
    lines += [
        "",
        "| Refusal | Operators | Refused | Rule | Check | Test |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for k, (rule, refusal) in enumerate(solver_rows(), 1):
        mark = "c" if refusal.beside or refusal.when else "R"
        where = refusal.when or "whatever the definition"
        if refusal.beside:
            where = "beside " + " or ".join(named(law) for law in refusal.beside)
        laws = ", ".join(str(number(law)) for law in refusal.laws)
        test = "none" if refusal.test is None else f"`{refusal.test or rule['test']}`"
        cites = f"`{rule['check']}` | {test}"
        lines.append(f"| {mark}{k} | {laws} | {where} | {rule['rule']} | {cites} |")
    return lines


def document_block(text):
    start, end = text.index(START), text.index(END) + len(END)
    return text[start:end]


